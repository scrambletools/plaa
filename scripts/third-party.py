"""Writes docs/THIRD-PARTY.md: the libraries and fonts plaa is built
from or carries, with their licenses. Run from the repository root after
changing dependencies:

    python3 scripts/third-party.py

With --check it writes nothing and fails when the file is out of date,
as CI runs it.
"""

import json
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "docs" / "THIRD-PARTY.md"

# What is built in or carried but not a Rust crate, or a crate patched.
BUNDLED = [
    ("FFmpeg", "GPL-3.0-or-later, as built with its GPL parts", "plays, decodes and encodes; the system's on Linux, carried on Windows (BtbN's build) and macOS (Homebrew's) with the libraries it is built with, each package naming them and carrying their licenses", "https://ffmpeg.org"),
    ("libass", "ISC", "ASS and SSA subtitles; the system's on Linux, carried on Windows and macOS", "https://github.com/libass/libass"),
    ("FreeType", "FTL OR GPL-2.0-or-later", "glyphs for libass; carried on Windows and macOS", "https://freetype.org"),
    ("HarfBuzz", "MIT", "text shaping for libass; carried on Windows and macOS", "https://harfbuzz.github.io"),
    ("FriBidi", "LGPL-2.1-or-later", "right to left text for libass; carried on Windows and macOS", "https://github.com/fribidi/fribidi"),
    ("Microsoft Visual C++ runtime", "Microsoft Visual Studio license, distributable code", "DLLs that libass and the libraries it needs load, carried on Windows as Microsoft signs them", "https://learn.microsoft.com/cpp/windows/redistributing-visual-cpp-files"),
    ("Roboto Flex", "OFL-1.1", "interface font, from scramble-ui", "https://github.com/googlefonts/roboto-flex"),
    ("Material Symbols Rounded", "Apache-2.0", "icons, from scramble-ui", "https://github.com/google/material-design-icons"),
    ("smithay-clipboard", "MIT", "vendored with a drag and drop patch, see vendor/PATCHES.md", "https://github.com/Smithay/smithay-clipboard"),
    ("iced_graphics, iced_widget", "MIT", "with right to left text input patches, from scramble-ui's vendor/", "https://github.com/iced-rs/iced"),
    ("winit", "Apache-2.0", "with patches from scramble-ui's vendor/", "https://github.com/rust-windowing/winit"),
]

OWN = {"plaa", "plaa-assist", "plaa-avb", "plaa-cast", "plaa-media", "plaa-store"}


def dependencies():
    """Every package plaa is built from, on any system, but plaa's own."""
    metadata = json.loads(
        subprocess.check_output(
            ["cargo", "metadata", "--format-version", "1", "--locked"], cwd=ROOT
        )
    )
    packages = {package["id"]: package for package in metadata["packages"]}
    nodes = {node["id"]: node for node in metadata["resolve"]["nodes"]}
    root = next(
        package_id for package_id, package in packages.items() if package["name"] == "plaa"
    )
    seen, stack = set(), [root]
    while stack:
        package_id = stack.pop()
        if package_id in seen:
            continue
        seen.add(package_id)
        for dependency in nodes[package_id]["deps"]:
            # Build scripts and normal dependencies end up in the programs
            # or shape them; development dependencies do not.
            if any(kind["kind"] in (None, "build") for kind in dependency["dep_kinds"]):
                stack.append(dependency["pkg"])
    return sorted(
        (packages[package_id] for package_id in seen if packages[package_id]["name"] not in OWN),
        key=lambda package: (package["name"], package["version"]),
    )


def document():
    crates = dependencies()
    by_license = defaultdict(list)
    for package in crates:
        license = package.get("license") or "see the crate"
        by_license[license].append(f'{package["name"]} {package["version"]}')
    lines = [
        "# Third-party components",
        "",
        "plaa is licensed under the GNU General Public License, version 3 or",
        "later (see LICENSE). It is built from the components below, each",
        "under its own license. This file is generated by",
        "`scripts/third-party.py`.",
        "",
        "## Bundled libraries and fonts",
        "",
        "| Component | License | Use |",
        "|---|---|---|",
    ]
    for name, license, use, url in BUNDLED:
        lines.append(f"| [{name}]({url}) | {license} | {use} |")
    lines += [
        "",
        f"## Rust crates ({len(crates)})",
        "",
        "Grouped by license, as each crate declares it.",
        "",
    ]
    for license in sorted(by_license, key=lambda license: (-len(by_license[license]), license)):
        lines.append(f"### {license}")
        lines.append("")
        lines.append(", ".join(by_license[license]))
        lines.append("")
    return "\n".join(lines), len(crates)


def main():
    text, count = document()
    if "--check" in sys.argv[1:]:
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            print(
                f"{OUTPUT.relative_to(ROOT)} is out of date: run python3 scripts/third-party.py",
                file=sys.stderr,
            )
            sys.exit(1)
        return
    OUTPUT.write_text(text)
    print(f"wrote {OUTPUT.relative_to(ROOT)}: {count} crates")


if __name__ == "__main__":
    main()
